export function getCountryNameArabic(countryCode: unknown, fallback = "ye"): string {
  let clean = String(countryCode ?? "")
    .trim()
    .toLowerCase()
    .replace("il", "ps");
  if (!clean || clean === "--" || clean === "xx" || clean === "t1") {
    clean = fallback ? fallback.toLowerCase() : "";
  }
  if (!clean) return "اليمن";
  return COUNTRY_NAMES_AR[clean] || clean.toUpperCase();
}

export function resolveCountryFlagUrl(countryCode: unknown, fallback = "ye"): string {
  let clean = String(countryCode ?? "")
    .trim()
    .toLowerCase()
    .replace("il", "ps");
  if (!/^[a-z]{2,8}$/.test(clean) || clean === "xx" || clean === "t1") {
    clean = fallback ? fallback.toLowerCase() : "";
  }
  if (!clean) return "";
  return `/flag/${clean}.png`;
}
