async function main() {
  const mysqlConn = await mysql.createConnection({
    host: process.env.LEGACY_MYSQL_HOST || "127.0.0.1",
    port: Number(process.env.LEGACY_MYSQL_PORT || 3308),
    user: process.env.LEGACY_MYSQL_USER || "root",
    password: process.env.LEGACY_MYSQL_PASS || "",
    database: process.env.LEGACY_MYSQL_DB || "safarihost",
  });

  const { db } = getDb();
  console.log("[Migrate] Connected to legacy MySQL and target PostgreSQL 18.");

  for (const spec of MIGRATION_SPECS) {
    const [rows] = await mysqlConn.query<any[]>(`SELECT * FROM \`${spec.mysqlTable}\``);
    if (!rows.length) {
      console.log(`- ${spec.mysqlTable}: 0 rows (skipped)`);
      continue;
    }

    const batchSize = 200;
    for (let i = 0; i < rows.length; i += batchSize) {
      const slice = rows.slice(i, i + batchSize).map(spec.transform);
      await db.insert(spec.pgTableObj).values(slice).onConflictDoNothing();
    }

    if (spec.pkCol) {
      await db.execute(
        sql.raw(
          `SELECT setval(pg_get_serial_sequence('"${spec.pgTableName}"', '${spec.pkCol}'), COALESCE((SELECT MAX("${spec.pkCol}") FROM "${spec.pgTableName}"), 1), true);`
        )
      );
    }

    console.log(`+ ${spec.mysqlTable} -> ${spec.pgTableName}: ${rows.length} rows migrated`);
  }

  await mysqlConn.end();
  await closeDb();
  console.log("[Migrate] Completed all 39 tables successfully.");
}

main().catch((err) => {
  console.error("[Migrate] Failed:", err);
  process.exit(1);
});
